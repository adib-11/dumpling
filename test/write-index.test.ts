import assert from "node:assert/strict"
import fs from "node:fs"
import os from "node:os"
import path from "node:path"
import test from "node:test"
import { writeIndex } from "../src/write-index"

const expected = `# Index

Generated by \`bin/index\` from Page frontmatter after each Ingest. Never edit it, by hand or as the agent.

## people

| Page | Tags | Summary | Updated |
| --- | --- | --- | --- |
| [[rahim\\|রহিম]] | family | My cousin in Dhaka. | 2026-10-02 |

## works

| Page | Tags | Summary | Updated |
| --- | --- | --- | --- |
| [[a-video\\|A \\| B video]] |  | Pipe in alias and summary \\| here. | 2026-10-01 |
| [[atomic-habits\\|Atomic Habits]] | habits, self-help | Book by James Clear; read in 2025. | 2026-09-30 |

## topics

| Page | Tags | Summary | Updated |
| --- | --- | --- | --- |
| [[bare]] |  |  |  |
| [[sleep\\|Sleep]] |  | How I sleep. | 2026-10-03 |

## me

| Page | Tags | Summary | Updated |
| --- | --- | --- | --- |
| [[me\\|Adib]] | self | Self-observations. | 2026-10-04 |
`

test("writeIndex builds index.md from Page frontmatter", () => {
  const brain = fs.mkdtempSync(path.join(os.tmpdir(), "second brain-"))
  const wiki = path.join(brain, "vault", "wiki")
  fs.mkdirSync(path.join(wiki, "people"), { recursive: true })
  fs.mkdirSync(path.join(wiki, "works"), { recursive: true })
  fs.mkdirSync(path.join(wiki, "topics"), { recursive: true })
  fs.mkdirSync(path.join(wiki, "projects"), { recursive: true })

  fs.writeFileSync(
    path.join(wiki, "people", "rahim.md"),
    `---
type: person
aliases:
  - রহিম
  - Rahim
tags:
  - family
summary: My cousin in Dhaka.
updated: 2026-10-02
---

# রহিম
`,
  )
  fs.writeFileSync(
    path.join(wiki, "works", "atomic-habits.md"),
    `---
type: work
aliases: [Atomic Habits]
tags: [habits, self-help]
summary: "Book by James Clear; read in 2025."
updated: 2026-09-30
format: book
---

# Atomic Habits
`,
  )
  fs.writeFileSync(
    path.join(wiki, "works", "a-video.md"),
    `---
type: work
aliases:
  - A | B video
summary: Pipe in alias and summary | here.
updated: 2026-10-01
---
`,
  )
  fs.writeFileSync(
    path.join(wiki, "topics", "sleep.md"),
    `---
type: topic
aliases:
  - Sleep
tags:
summary: How I sleep.
updated: 2026-10-03
---
`,
  )
  fs.writeFileSync(path.join(wiki, "topics", "bare.md"), "no frontmatter\n")
  fs.writeFileSync(path.join(wiki, "topics", "notes.txt"), "not a Page\n")
  fs.writeFileSync(
    path.join(wiki, "me.md"),
    `---
type: person
aliases: [Adib]
tags: [self]
summary: Self-observations.
updated: 2026-10-04
---
`,
  )

  writeIndex(brain)
  const indexPath = path.join(wiki, "index.md")
  assert.equal(fs.readFileSync(indexPath, "utf8"), expected)

  writeIndex(brain)
  assert.equal(fs.readFileSync(indexPath, "utf8"), expected)
  assert.deepEqual(
    fs.readdirSync(wiki).filter((name) => name.endsWith(".tmp")),
    [],
  )
})

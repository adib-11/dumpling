import fs from "node:fs"
import path from "node:path"

const kinds = ["people", "works", "topics", "projects", "places"]

type Frontmatter = Record<string, string | string[]>

function unquote(value: string): string {
  const match = value.match(/^(["'])(.*)\1$/)
  return match ? match[2] : value
}

function frontmatter(file: string): Frontmatter {
  const lines = fs.readFileSync(file, "utf8").split(/\r?\n/)
  const fm: Frontmatter = {}
  if (!/^---\s*$/.test(lines[0] ?? "")) return fm
  let key: string | undefined
  for (let i = 1; i < lines.length; i++) {
    const line = lines[i]
    if (/^---\s*$/.test(line)) break
    const field = /^([\w-]+):\s*(.*?)\s*$/.exec(line)
    if (field) {
      key = field[1]
      const raw = field[2]
      const inline = /^\[(.*)\]$/.exec(raw)
      fm[key] = raw === "" ? [] : inline ? inline[1].split(/\s*,\s*/).filter((part) => part.length > 0).map(unquote) : unquote(raw)
      continue
    }
    const current = key ? fm[key] : undefined
    if (Array.isArray(current)) {
      const item = /^\s+-\s*(.*?)\s*$/.exec(line)
      if (item) current.push(unquote(item[1]))
    }
  }
  return fm
}

function cell(value: string | string[] | undefined): string {
  const text = Array.isArray(value) ? value.join(", ") : (value ?? "")
  return text.replaceAll("|", "\\|")
}

function pagesIn(dir: string): string[] {
  if (!fs.existsSync(dir)) return []
  return fs
    .readdirSync(dir)
    .filter((name) => name.endsWith(".md"))
    .sort()
    .map((name) => path.join(dir, name))
}

export function writeIndex(brain: string): void {
  const wiki = path.join(brain, "vault", "wiki")
  const sections = kinds.map((kind) => ({ name: kind, pages: pagesIn(path.join(wiki, kind)) }))
  const me = path.join(wiki, "me.md")
  sections.push({ name: "me", pages: fs.existsSync(me) ? [me] : [] })

  let out =
    "# Index\n\nGenerated by `bin/index` from Page frontmatter after each Ingest. Never edit it, by hand or as the agent.\n"
  for (const section of sections) {
    if (section.pages.length === 0) continue
    out += `\n## ${section.name}\n\n| Page | Tags | Summary | Updated |\n| --- | --- | --- | --- |\n`
    for (const file of section.pages) {
      const name = path.basename(file, ".md")
      const fm = frontmatter(file)
      const aliases = fm.aliases
      const alias = Array.isArray(aliases) ? aliases[0] : aliases
      const link = alias ? `[[${name}\\|${cell(alias)}]]` : `[[${name}]]`
      out += `| ${[link, cell(fm.tags), cell(fm.summary), cell(fm.updated)].join(" | ")} |\n`
    }
  }

  const tmp = path.join(wiki, "index.md.tmp")
  fs.writeFileSync(tmp, out)
  fs.renameSync(tmp, path.join(wiki, "index.md"))
}
